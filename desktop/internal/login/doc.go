// Package login 은 구글 로그인을 앱 밖(기본 브라우저)에서 처리한다.
//
// 구글은 앱 내장 웹뷰에서의 로그인을 막는다. 그래서:
//   1. 127.0.0.1 의 빈 포트에 잠깐 HTTP 서버를 띄운다 (콜백 받을 곳)
//   2. 기본 브라우저로 구글 로그인 페이지를 연다
//   3. 로그인이 끝나면 구글이 127.0.0.1:포트/callback?code=... 로 돌려보낸다
//   4. code 를 서버에 넘겨 세션 토큰을 받고, 임시 서버를 닫는다
//
// 3번에서 "요청이 올 때까지 기다리기"를 채널로 하게 된다. 고루틴·채널 첫 실전.
